STRUCTS = [
    (
        "party_struct",
        "wPartyMon1",
        "wPartyMon2",
        "One of the six Pokemon you carry. Also the shape the link cable sends, "
        "and the shape a trainer's team is built in.",
    ),
    (
        "box_struct",
        "wBoxMon1",
        "wBoxMon2",
        "One of the twenty in a PC box: `party_struct` with the level and the five "
        "computed stats removed, because a stored Pokemon's stats are recalculated "
        "when it is withdrawn.",
    ),
    (
        "battle_struct",
        "wBattleMon",
        None,
        "The active Pokemon while a battle runs. Not the party shape: original "
        "trainer, experience and stat experience are gone, so the level and the "
        "stats sit at different offsets. Confusing the two is the classic way to "
        "produce a level 6,400 Pokemon.",
    ),
    (
        "battle_struct (opponent)",
        "wEnemyMon",
        None,
        "The same 29 bytes for the other side.",
    ),
    (
        "day-care lodger",
        "wDayCareMon",
        None,
        "One `box_struct` on its own, with its name and OT beside it.",
    ),
]


def struct_block(rows) -> str:
    by_symbol = {r["symbol"]: r for r in rows}
    out = []
    for title, first, second, blurb in STRUCTS:
        base = by_symbol.get(first)
        if base is None:
            continue
        fields = [
            r
            for r in rows
            if r["symbol"].startswith(first)
            and r["symbol"] != first
            and r["region"] == base["region"]
            and r["addr_i"] >= base["addr_i"]
        ]
        # Keep only the fields of *this* slot: everything up to the next slot.
        if second and second in by_symbol:
            end = by_symbol[second]["addr_i"]
        else:
            end = max((f["addr_i"] + max(f["len_i"], 1)) for f in fields) if fields else base["addr_i"]
        fields = [f for f in fields if f["addr_i"] < end]
        fields.sort(key=lambda r: (r["addr_i"], r["symbol"]))
        total = end - base["addr_i"]
        out.append(f"### `{title}` — {total} bytes")
        out.append("")
        out.append(blurb)
        out.append("")
        out.append(f"Base `{first}` at `{base['addr']}`.")
        out.append("")
        out.append("| offset | bytes | field | notes |")
        out.append("|---:|---:|---|---|")
        seen = set()
        for f in fields:
            off = f["addr_i"] - base["addr_i"]
            names = [g["symbol"] for g in fields if g["addr_i"] == f["addr_i"]]
            if f["addr_i"] in seen:
                continue
            seen.add(f["addr_i"])
            label = " / ".join(f"`{n[len(first):] or n}`" for n in names)
            here = [g["desc"] for g in fields if g["addr_i"] == f["addr_i"] and g["desc"]]
            out.append(f"| {off} | {size(f['len_i'])} | {label} | {here[0] if here else ''} |")
        out.append("")
    return block("structs", out)


# ---------------------------------------------------------------------------
# splicing
# ---------------------------------------------------------------------------


def splice(text: str, name: str, body: str, stub: str) -> str:
    """Replace one generated block inside `text`.

    Operates on the text it is handed, never on the file — a page may carry
    several blocks, and re-reading the file between them would leave only the
    last one applied.  A page that has lost its markers is rebuilt from `stub`
    rather than silently keeping a stale table.
    """
    begin, end = BEGIN.format(name), END.format(name)
    if begin not in text or end not in text:
        text = stub
    i = text.index(begin)
    j = text.index(end) + len(end)
    return text[:i] + body + text[j:]


PAGES: list[tuple[str, str]] = []


def check_anchors() -> list[str]:
    """Every `page.md#s-…` / `#a-…` link must land on an anchor that exists.

    `make docs-check` verifies that a link's *file* exists and deliberately does
    not look at fragments, so an index of 2,400 anchored links would otherwise
    be able to rot silently. It did: aliases were linked before they were given
    anchors, and 370 links pointed at nothing.
    """
    import collections

    anchors: dict[str, set[str]] = collections.defaultdict(set)
    for path in sorted(os.listdir(DIR)):
        if not path.endswith(".md"):
            continue
        text = open(os.path.join(DIR, path), encoding="utf-8").read()
        for m in re.finditer(r'<a id="([^"]+)">', text):
            anchors[path].add(m.group(1))
    broken = []
    for path in sorted(os.listdir(DIR)):
        if not path.endswith(".md"):
            continue
        text = open(os.path.join(DIR, path), encoding="utf-8").read()
        for m in re.finditer(r"\]\((([a-z0-9-]+\.md))#([^)]+)\)", text):
            target, frag = m.group(1), m.group(3)
            if frag.startswith(("s-", "a-")) and frag not in anchors.get(target, set()):
                broken.append(f"{path} -> {target}#{frag}")
    return broken


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows = read_atlas()
    jobs = []

    # README
    jobs.append(
        (
            "README.md",
            [("coverage", coverage_block(rows)), ("evidence", evidence_block(rows)),
             ("chapters", chapter_index_block(rows))],
            readme_stub(),
        )
    )
    jobs.append(("by-address.md", [("addresses", address_index_block(rows))], index_stub("address")))
    jobs.append(("by-name.md", [("names", name_index_block(rows))], index_stub("name")))
    jobs.append(("structures.md", [("structs", struct_block(rows))], structures_stub()))
    present = {r["group"] for r in rows}
    for name in chapters_mod.CHAPTERS:
        if name not in present:
            continue
        jobs.append((f"{name}.md", [("table", chapter_table(rows, name))], chapter_stub(name)))

    stale = []
    for rel, blocks, stub in jobs:
        path = os.path.join(DIR, rel)
        before = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        text = before if before is not None else stub
        for bname, body in blocks:
            text = splice(text, bname, body, stub)
        if text != before:
            stale.append(rel if before is not None else f"{rel} (new)")
        if not args.check:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(text)

    broken = check_anchors()
    if broken:
        print("FAIL — the atlas pages contain dead anchor links:")
        for b in broken[:10]:
            print(f"  {b}")
        if len(broken) > 10:
            print(f"  ... and {len(broken) - 10} more")
        return 1

    if args.check:
        if stale:
            print("FAIL — the atlas pages are stale; run `make gen1-atlas`:")
            for s in stale:
                print(f"  {s}")
            return 1
        print(f"OK — {len(jobs)} atlas pages match {os.path.relpath(ATLAS, REPO)}")
        return 0

    print(f"Wrote {len(jobs)} pages from {len(rows):,} atlas entries")
    return 0


# ---------------------------------------------------------------------------
# stubs — the shape of a page the first time it is generated.  Everything
# outside the markers is preserved afterwards, so this is a starting point, not
# a template that overwrites your writing.
# ---------------------------------------------------------------------------


def readme_stub() -> str:
    return f"""# The Gen 1 memory atlas

[← Gen 1 area](../README.md)

Placeholder — see the generated blocks below.

## Coverage

{block("coverage", [])}

## Evidence

{block("evidence", [])}

## Chapters

{block("chapters", [])}
"""


def index_stub(kind: str) -> str:
    name = "address" if kind == "address" else "name"
    return f"""# The atlas, by {name}

[← the atlas](README.md)

{block("addresses" if kind == "address" else "names", [])}
"""


def structures_stub() -> str:
    return f"""# The structures

[← the atlas](README.md)

{block("structs", [])}
"""


def chapter_stub(name: str) -> str:
    blurb = chapters_mod.CHAPTERS[name]
    return f"""# {name}

[← the atlas](README.md) · [by address](by-address.md) · [by name](by-name.md)

{blurb}

{block("table", [])}
"""


