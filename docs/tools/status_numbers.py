def count(path: str | list[str], group: str | None = None) -> tuple[int, int]:
    """PASS / total rows of one or more baseline files, optionally one group.

    A row whose verdict is `SKIP` counts in NEITHER column. Those exist only in
    the c-sp baselines, where each one names a ROM this repository deliberately
    does not score (a Gambatte test upstream itself disables, a state dumper, a
    test that needs a human pressing buttons). Counting them as failures would
    invent a denominator nobody measures; dropping them silently would hide
    them. They are in the baseline, and the baseline says why.
    """
    passed = total = 0
    for p in [path] if isinstance(path, str) else path:
        with open(os.path.join(ROOT, "testharness", p), encoding="utf-8") as f:
            for line in f:
                if not line.strip() or line.startswith("#") or "=" not in line:
                    continue
                key, verdict = line.split("=", 1)
                if group is not None and key.split("/")[0] != group:
                    continue
                verdict = verdict.strip()
                if verdict.startswith("SKIP"):
                    continue
                total += 1
                if verdict.startswith("PASS"):
                    passed += 1
    return passed, total


def pixels(path: str) -> int:
    """Total Mealybug shade-rank distance across every row of one baseline.

    At three-of-seventy-nine a PASS/FAIL count is a flat wall that cannot show a
    picture engine getting closer, so the baselines record how many of the
    23,040 pixels differ. Summing them is the honest way to compare the two
    modes on a suite neither of them sweeps.
    """
    total = 0
    with open(os.path.join(ROOT, "testharness", path), encoding="utf-8") as f:
        for line in f:
            if line.lstrip().startswith("#"):
                continue
            m = re.search(r"(\d+)/23040 pixels differ", line)
            if m:
                total += int(m.group(1))
    return total


