        "|---|---:|---:|---|",
        row("In-repo harness — Blargg + dmg-acid2", "harness",
            "CPU instructions, memory/interrupt timing, sound hardware, a reference picture"),
        row("[Mooneye GB](measured/scoreboard.md#mooneye-gb--every-remaining-failure-is-a-ppu-test) — `acceptance`",
            "mooneye_acceptance", "core timing, interrupts, boot state"),
