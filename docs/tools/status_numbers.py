#!/usr/bin/env python3
"""status_numbers — keep the status page's suite scores derived, never hand-copied.

The status page ([docs/status.md](../status.md), plus the Pages-ready HTML at
docs/status/index.html) quotes the score of every accuracy suite. Every one of
those figures is derivable from the checked-in baselines under `testharness/`
— the baselines ARE the expectations (each row is the ROM's own verdict), so a
hand-copied table is wrong the day after the next re-bless.

This tool re-derives the counts and either rewrites the pages (`make status`)
or verifies them (`--check`, run by `make docs-check`, which is in CI). If a
baseline moves and the status page was not regenerated in the same commit, CI
goes red — that is the point.

Two numbers on the page are deliberately NOT managed here, because they are not
derivable from any baseline: the GB Emulator Shootout score (measured through
their manifest and screenshot comparison — see docs/shootout.md) and the other
emulators' Mealybug scores (published board figures). Both are labelled with
where they come from on the page itself.

Usage:
    status_numbers.py            # rewrite docs/status.md + docs/status/index.html
    status_numbers.py --check    # verify only; exit 1 on any drift
"""
from __future__ import annotations

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))  # docs/tools -> repo root
MD = os.path.join(ROOT, "docs", "status.md")
HTML = os.path.join(ROOT, "docs", "status", "index.html")

BEGIN = "<!-- suite-scores:begin (generated by docs/tools/status_numbers.py — edit the baselines, not this table) -->"
END = "<!-- suite-scores:end -->"


def count(path: str, group: str | None = None) -> tuple[int, int]:
    """PASS / total rows of one baseline file, optionally one key-prefix group."""
    passed = total = 0
    with open(os.path.join(ROOT, "testharness", path), encoding="utf-8") as f:
        for line in f:
            if not line.strip() or line.startswith("#") or "=" not in line:
                continue
            key, verdict = line.split("=", 1)
            if group is not None and key.split("/")[0] != group:
                continue
            total += 1
            if verdict.strip().startswith("PASS"):
                passed += 1
    return passed, total


def derive() -> dict[str, tuple[int, int]]:
    return {
        "harness": count("baseline.txt"),
        "mooneye_acceptance": count("mooneye_baseline.txt", "acceptance"),
        "mooneye_emulator_only": count("mooneye_baseline.txt", "emulator-only"),
        "mooneye_cgb": count("mooneye_cgb_baseline.txt"),
        "samesuite": count("samesuite_baseline.txt"),
        "cpp": count("cpp_baseline.txt"),
        "mealybug": count("mealybug_baseline.txt"),
        # The non-default (accurate) PPU engine, scored separately:
        "mooneye_acceptance_accurate": count("mooneye_accurate_baseline.txt", "acceptance"),
        "mealybug_accurate": count("mealybug_accurate_baseline.txt"),
    }


def md_block(n: dict[str, tuple[int, int]]) -> str:
    """The generated section of docs/status.md, markers included."""

    def row(name: str, key: str, judged: str) -> str:
        p, t = n[key]
        return f"| {name} | **{p}** / {t} | {judged} |"

    lines = [
        BEGIN,
        "| Suite | Score | What it measures |",
        "|---|---:|---|",
        row("In-repo harness — Blargg + dmg-acid2", "harness",
            "CPU instructions, memory/interrupt timing, sound hardware, a reference picture"),
        row("[Mooneye GB](measured/scoreboard.md#mooneye-gb--every-remaining-failure-is-a-ppu-test) — `acceptance`",
            "mooneye_acceptance", "core timing, interrupts, boot state"),
        row("Mooneye GB — `emulator-only`", "mooneye_emulator_only", "cartridge mappers"),
        row("Mooneye GB — `misc` (CGB)", "mooneye_cgb", "Color-specific behaviour"),
        row("[SameSuite](measured/scoreboard.md)", "samesuite",
            "audio hardware, DMA, Super Game Boy"),
        row("CasualPokePlayer (`cpp`)", "cpp", "MBC3 real-time clock + SGB"),
        row("[Mealybug Tearoom](measured/scoreboard.md)", "mealybug",
            "mid-scanline picture timing — pixel-exact rows"),
    ]
    pa, ta = n["mooneye_acceptance_accurate"]
    pm, tm = n["mealybug_accurate"]
    lines += [
        "",
        f"The selectable per-pixel PPU engine (`GB_PPU=accurate`) scores **{pa}/{ta}** on Mooneye"
        f" `acceptance` and **{pm}/{tm}** on Mealybug — it trades rows with the default rather than"
        " dominating it, which is why the default has not moved"
        " ([why](measured/scoreboard.md#the-accurate-engine-scores-differently--and-trades-rather-than-dominating)).",
        END,
    ]
    return "\n".join(lines)


# HTML row-name prefix -> suite key. The Shootout row carries no key: not
# baseline-derived, left alone (and its bar/score are hand-measured).
HTML_ROWS = {
    "In-repo harness": "harness",
    "Mooneye GB &mdash; acceptance": "mooneye_acceptance",
    "Mooneye GB &mdash; emulator-only": "mooneye_emulator_only",
    "Mooneye GB &mdash; CGB misc": "mooneye_cgb",
    "SameSuite": "samesuite",
    "CasualPokePlayer": "cpp",
    "Mealybug Tearoom": "mealybug",
}

ROW_RE = re.compile(
    r'(<div class="name">(?P<name>[^<]+?)(?:<em>.*?</em>)?</div>\s*'
    r'<div class="score">)(?P<p>\d+)(<span>/)(?P<t>\d+)(</span></div>\s*'
    r'<div class="bar[^"]*"><i style="width:)(?P<w>[\d.]+)(%")',
    re.S,
)


def rewrite_html(text: str, n: dict[str, tuple[int, int]]) -> str:
    def sub(m: re.Match) -> str:
        key = next((k for pre, k in HTML_ROWS.items() if m.group("name").startswith(pre)), None)
        if key is None:
            return m.group(0)
        p, t = n[key]
        width = f"{100 * p / t:.1f}".rstrip("0").rstrip(".")
        return f"{m.group(1)}{p}{m.group(4)}{t}{m.group(6)}{width}{m.group(8)}"

    return ROW_RE.sub(sub, text)


def replace_md(text: str, block: str) -> str:
    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    return text[:start] + block + text[end:]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify only; do not write")
    args = ap.parse_args()

    n = derive()
    problems = []

    md_text = open(MD, encoding="utf-8").read()
    if BEGIN not in md_text or END not in md_text:
        print(f"FAIL — markers missing from {os.path.relpath(MD, ROOT)}")
        return 1
    new_md = replace_md(md_text, md_block(n))

    html_text = open(HTML, encoding="utf-8").read()
    new_html = rewrite_html(html_text, n)
    matched = {k for pre, k in HTML_ROWS.items()
               for m in ROW_RE.finditer(html_text) if m.group("name").startswith(pre)}
    if matched != set(HTML_ROWS.values()):
        problems.append(f"index.html: expected suite rows not found: "
                        f"{sorted(set(HTML_ROWS.values()) - matched)}")

    if args.check:
        if new_md != md_text:
            problems.append("docs/status.md suite table disagrees with the baselines — run `make status`")
        if new_html != html_text:
            problems.append("docs/status/index.html scores disagree with the baselines — run `make status`")
        if problems:
            print("FAIL:")
            for p in problems:
                print("  -", p)
            return 1
        scores = ", ".join(f"{k} {p}/{t}" for k, (p, t) in n.items())
        print(f"OK — status page matches the baselines ({scores}).")
        return 0

    changed = []
    if new_md != md_text:
        open(MD, "w", encoding="utf-8").write(new_md)
        changed.append("docs/status.md")
    if new_html != html_text:
        open(HTML, "w", encoding="utf-8").write(new_html)
        changed.append("docs/status/index.html")
    for p in problems:
        print("Warning:", p)
    print(f"Updated: {', '.join(changed) if changed else 'nothing (already current)'}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
