        row("CasualPokePlayer (`cpp`)", "cpp", "MBC3 real-time clock + SGB"),
        row("[Mealybug Tearoom](measured/scoreboard.md)", "mealybug",
            "mid-scanline picture timing — pixel-exact rows"),
        row("[Gambatte](measured/scoreboard.md#the-c-sp-aggregation--thirteen-suites-measured-for-the-first-time)",
            "csp_gambatte", "the largest suite there is — mostly PPU, per console"),
        row("[GBMicrotest](measured/scoreboard.md#the-c-sp-aggregation--thirteen-suites-measured-for-the-first-time)",
            "csp_gbmicrotest", "low-level timing probes, each writing its own verdict byte"),
        row("[AGE test roms](measured/scoreboard.md#the-c-sp-aggregation--thirteen-suites-measured-for-the-first-time)",
            "csp_age", "timing, per console revision"),
        row("Mooneye GB — wilbertpol fork", "csp_wilbertpol",
            "the 2016 suite, a different population from Gekkio's"),
        row("cgb-acid2 + cgb-acid-hell", "csp_acid",
            "the Color siblings of dmg-acid2, judged in colour"),
        row("Bully / Scribbltests / Strikethrough / TurtleTests / little-things-gb / MBC3 Tester / rtc3test",
            "csp_small", "screenshot-judged odds and ends, plus the cartridge clock"),
