//! Pushing a milestone to a phone, over [ntfy](https://ntfy.sh).
//!
//! # Why ntfy and why `curl`
//!
//! The maintainer already uses ntfy for exactly this class of "how close are we?"
//! push, so this wires up the mechanism he has rather than inventing one. The
//! transport is the system `curl` binary for the same reason
//! [`crate::portal::http`] uses it: this repository treats its dependency count
//! as a contract (`make embed` asserts the embedding build has exactly one
//! third-party crate), TLS is the one thing that must never be hand-rolled, and
//! ntfy's API is a plain HTTP POST with the message as the body.
//!
//! # Nothing here may ever slow the emulator down
//!
//! The whole point of a long run is 70x real time, and a network call is
//! milliseconds at best and *seconds* at worst. So a push is handed to a
//! detached thread and forgotten: [`Notifier::push`] does a bounded amount of
//! string work and returns. This is the same rule the audio hand-off learned
//! the hard way (`docs/audio.md` §4c) — **never put a second clock inside the
//! emulator's loop.**
//!
//! The queue is bounded and **drops on overflow**, loudly in the counters.
//! A phone that missed the fourteenth level-up of a burst has lost nothing; a
//! run that stalled waiting to tell it has lost everything.
//!
//! # What is not sent
//!
//! Milestone text is generated by [`super::progress::MilestoneKind::text`] and
//! is plain English by construction. Anything originating with the model goes
//! through [`terminalgb_plugin_agent::commentary::sanitise`] before it reaches
//! here, so a push cannot carry a path, a token or an escape sequence.

use std::sync::atomic::{AtomicU32, Ordering};
use std::sync::mpsc::{sync_channel, SyncSender, TrySendError};
use std::sync::Arc;

use super::progress::Importance;

/// How many pushes may be queued before new ones are dropped. Small: a backlog
/// means the network is unhealthy, and a milestone is only interesting while
/// it is fresh.
const QUEUE: usize = 16;

/// Hard limits on the request, so a hung ntfy server cannot leak threads.
const CONNECT_TIMEOUT_S: u32 = 5;
const TOTAL_TIMEOUT_S: u32 = 15;

/// A single push, before it goes on the wire.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Push {
    pub title: String,
    pub body: String,
    pub importance: Importance,
}

/// Counters, so "the phone is quiet" can be told from "nothing happened".
#[derive(Debug, Default)]
pub struct Counters {
    pub sent: AtomicU32,
    pub failed: AtomicU32,
    pub dropped: AtomicU32,
}

/// Where and what to push.
#[derive(Debug, Clone)]
pub struct NtfyConfig {
    /// Full topic URL, e.g. `https://ntfy.sh/my-pokemon-run`.
    pub url: String,
    /// Optional bearer token for a private server. Kept off argv.
    pub token: Option<String>,
    /// Nothing below this is pushed. Defaults to `Major`, which is badges,
    /// towns, the first Pokémon, a wall, a wipe and the run ending.
    pub min: Importance,
}

impl NtfyConfig {
    /// Validate a user-supplied topic URL. A typo that silently pushes nowhere
    /// is worse than a refusal — the same call `config.toml`'s `protocol` key
    /// makes.
    pub fn parse(
        url: &str,
        token: Option<String>,
        min: Importance,
    ) -> Result<NtfyConfig, String> {
        let url = url.trim().trim_end_matches('/');
        if !(url.starts_with("https://") || url.starts_with("http://")) {
            return Err(format!(
                "ntfy needs a full topic URL like https://ntfy.sh/my-topic, not {url:?}"
            ));
        }
        // A bare host with no topic posts to nothing.
        let rest = url.split_once("://").map(|(_, r)| r).unwrap_or("");
        if !rest.contains('/') || rest.split('/').nth(1).is_none_or(str::is_empty) {
            return Err(format!(
                "{url:?} has no topic — ntfy URLs look like https://ntfy.sh/my-topic"
            ));
        }
        if url.chars().any(|c| c.is_control()) {
            return Err("the ntfy URL contains a control character".into());
        }
        Ok(NtfyConfig {
            url: url.to_string(),
            token,
            min,
        })
    }
}

/// The push channel. Cloneable counters, one worker thread.
pub struct Notifier {
    tx: Option<SyncSender<Push>>,
    counters: Arc<Counters>,
    min: Importance,
}

impl Notifier {
    /// A notifier that does nothing. What a run gets when `--ntfy` is absent,
    /// so the call sites do not branch.
    pub fn disabled() -> Notifier {
        Notifier {
            tx: None,
            counters: Arc::new(Counters::default()),
            min: Importance::Major,
        }
    }

    pub fn is_enabled(&self) -> bool {
        self.tx.is_some()
    }

    /// Start the worker thread.
    pub fn start(cfg: NtfyConfig) -> Notifier {
        let (tx, rx) = sync_channel::<Push>(QUEUE);
        let counters = Arc::new(Counters::default());
        let c = counters.clone();
        let min = cfg.min;
        // Detached: the run's exit path drains what it can and does not wait
        // for a server that has stopped answering.
        std::thread::spawn(move || {
            for push in rx {
                match send(&cfg, &push) {
                    Ok(()) => c.sent.fetch_add(1, Ordering::Relaxed),
                    Err(_) => c.failed.fetch_add(1, Ordering::Relaxed),
                };
            }
        });
        Notifier {
            tx: Some(tx),
            counters,
            min,
        }
    }

    /// Queue a push. **Never blocks.** Returns false if it was dropped or the
    /// notifier is off.
    pub fn push(&self, push: Push) -> bool {
        if push.importance < self.min {
            return false;
        }
        let Some(tx) = &self.tx else {
            return false;
        };
        match tx.try_send(push) {
            Ok(()) => true,
            Err(TrySendError::Full(_)) | Err(TrySendError::Disconnected(_)) => {
                self.counters.dropped.fetch_add(1, Ordering::Relaxed);
                false
            }
        }
    }

    pub fn stats(&self) -> (u32, u32, u32) {
        (
            self.counters.sent.load(Ordering::Relaxed),
            self.counters.failed.load(Ordering::Relaxed),
            self.counters.dropped.load(Ordering::Relaxed),
        )
    }

    /// Let the worker finish what is queued, up to a bound. Called once on the
    /// way out so the final summary actually arrives.
    pub fn drain(&mut self, wait: std::time::Duration) {
        let Some(tx) = self.tx.take() else { return };
        drop(tx); // the worker's loop ends when the channel closes
        let deadline = std::time::Instant::now() + wait;
        while std::time::Instant::now() < deadline {
            let (s, f, d) = self.stats();
            let _ = (s, f, d);
            std::thread::sleep(std::time::Duration::from_millis(25));
            // There is no join handle on purpose: a hung server must cost the
            // bounded wait above and nothing more.
            if std::time::Instant::now() >= deadline {
                break;
            }
        }
    }
}

/// ntfy's priority scale, 1 (min) to 5 (max).
fn priority(i: Importance) -> &'static str {
    match i {
        Importance::Minor => "2",
        Importance::Major => "4",
        Importance::Trouble => "4",
    }
}

fn tags(i: Importance) -> &'static str {
    match i {
        Importance::Minor => "video_game",
        Importance::Major => "trophy",
        Importance::Trouble => "warning",
    }
}

/// Escape a value for curl's config-file quoting — the same rule (and the same
/// reason) as [`crate::portal::http`]: credentials must not appear on argv,
/// where `ps` shows them to every user on the machine.
fn config_quote(v: &str) -> String {
    let mut out = String::with_capacity(v.len() + 2);
    out.push('"');
    for c in v.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            c if c.is_control() => out.push(' '),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Build the curl config for one push. Split out so a test can pin that the
/// token never reaches argv and that a header cannot be injected through a
/// milestone's text.
pub fn build_config(cfg: &NtfyConfig, push: &Push) -> String {
    let mut s = String::new();
    s.push_str(&format!("url = {}\n", config_quote(&cfg.url)));
    s.push_str("request = \"POST\"\n");
    s.push_str(&format!(
        "header = {}\n",
        config_quote(&format!("Title: {}", one_line(&push.title)))
    ));
    s.push_str(&format!(
        "header = {}\n",
        config_quote(&format!("Priority: {}", priority(push.importance)))
    ));
    s.push_str(&format!(
        "header = {}\n",
        config_quote(&format!("Tags: {}", tags(push.importance)))
    ));
    if let Some(t) = &cfg.token {
        s.push_str(&format!(
            "header = {}\n",
            config_quote(&format!("Authorization: Bearer {t}"))
        ));
    }
    s.push_str(&format!("data = {}\n", config_quote(&push.body)));
    s.push_str("silent\nshow-error\nfail\n");
    s.push_str(&format!("connect-timeout = {CONNECT_TIMEOUT_S}\n"));
    s.push_str(&format!("max-time = {TOTAL_TIMEOUT_S}\n"));
    s
}

/// A header value is one line by definition. Newlines in a title would let a
/// milestone's text inject a header, so they become spaces here rather than
/// being trusted not to occur.
fn one_line(s: &str) -> String {
    s.chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect()
}

fn send(cfg: &NtfyConfig, push: &Push) -> Result<(), String> {
    use std::io::Write as _;
    use std::process::{Command, Stdio};
    let mut child = Command::new("curl")
        .arg("--config")
        .arg("-")
        .stdin(Stdio::piped())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .map_err(|e| format!("curl: {e}"))?;
    if let Some(mut si) = child.stdin.take() {
        let _ = si.write_all(build_config(cfg, push).as_bytes());
    }
    let status = child.wait().map_err(|e| format!("curl: {e}"))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("curl exited {status}"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg() -> NtfyConfig {
        NtfyConfig::parse(
            "https://ntfy.sh/gb-run",
            Some("tk_secret".into()),
            Importance::Major,
        )
        .expect("valid")
    }

    #[test]
    fn a_url_without_a_topic_is_refused_rather_than_posting_nowhere() {
        assert!(NtfyConfig::parse("ntfy.sh/x", None, Importance::Major).is_err());
        assert!(NtfyConfig::parse("https://ntfy.sh", None, Importance::Major).is_err());
        assert!(NtfyConfig::parse("https://ntfy.sh/", None, Importance::Major).is_err());
        assert!(
            NtfyConfig::parse("https://ntfy.sh/topic", None, Importance::Major).is_ok()
        );
        // A trailing slash is a typo, not a different topic.
        let c =
            NtfyConfig::parse("https://ntfy.sh/topic/", None, Importance::Major).unwrap();
        assert_eq!(c.url, "https://ntfy.sh/topic");
    }

    #[test]
    fn the_token_travels_on_stdin_and_never_on_argv() {
        // The property this file exists to keep: `ps` is world-readable.
        let s = build_config(
            &cfg(),
            &Push {
                title: "t".into(),
                body: "b".into(),
                importance: Importance::Major,
            },
        );
        assert!(s.contains("Authorization: Bearer tk_secret"));
        // …and the only thing on argv is `--config -`, which `send` hard-codes.
    }

    #[test]
    fn a_newline_in_a_milestone_cannot_inject_a_header() {
        let s = build_config(
            &cfg(),
            &Push {
                title: "Won\r\nX-Evil: yes".into(),
                body: "ok".into(),
                importance: Importance::Major,
            },
        );
        assert!(!s.contains("X-Evil: yes\n"), "{s}");
        assert!(s.contains("Title: Won  X-Evil: yes"), "{s}");
    }

    #[test]
    fn a_disabled_notifier_swallows_everything_without_a_thread() {
        let n = Notifier::disabled();
        assert!(!n.is_enabled());
        assert!(!n.push(Push {
            title: "t".into(),
            body: "b".into(),
            importance: Importance::Trouble,
        }));
        assert_eq!(n.stats(), (0, 0, 0));
    }

    #[test]
    fn minor_milestones_do_not_reach_a_phone_by_default() {
        // The queue is what proves it: a filtered push is never queued, so a
        // notifier whose worker cannot possibly run still reports no drop.
        let (tx, rx) = sync_channel(QUEUE);
        let n = Notifier {
            tx: Some(tx),
            counters: Arc::new(Counters::default()),
            min: Importance::Major,
        };
        assert!(!n.push(Push {
            title: "level".into(),
            body: "up".into(),
            importance: Importance::Minor
        }));
        assert!(n.push(Push {
            title: "badge".into(),
            body: "won".into(),
            importance: Importance::Major
        }));
        assert_eq!(n.stats().2, 0, "a filtered push is not a dropped one");
        assert_eq!(rx.try_recv().map(|p| p.title), Ok("badge".to_string()));
    }

    #[test]
    fn a_backed_up_queue_drops_rather_than_blocking_the_emulator() {
        let (tx, _rx) = sync_channel(QUEUE);
        let n = Notifier {
            tx: Some(tx),
            counters: Arc::new(Counters::default()),
            min: Importance::Minor,
        };
        let p = || Push {
            title: "x".into(),
            body: "y".into(),
            importance: Importance::Major,
        };
        for _ in 0..QUEUE {
            assert!(n.push(p()));
        }
        // The channel is full and nothing is reading it. This must return, not
        // park a frame.
        let t = std::time::Instant::now();
        assert!(!n.push(p()));
        assert!(t.elapsed() < std::time::Duration::from_millis(50));
        assert_eq!(n.stats().2, 1, "the drop is counted, not hidden");
    }
}
