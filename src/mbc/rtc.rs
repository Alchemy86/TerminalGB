//! The MBC3 real-time clock.
//!
//! A real MBC3 cartridge carries its own 32768 Hz crystal and a coin cell, so
//! the clock runs at a fixed rate that has nothing to do with what the console
//! is doing — it keeps time while the game runs, while the console is paused,
//! and while it is switched off.
//!
//! The emulated equivalent has two halves, and getting either one wrong is
//! visible to a game:
//!
//! * **While the emulator runs**, the clock is driven by *emulated* time:
//!   exactly one second per [`CYCLES_PER_SECOND`] T-cycles of console time.
//!   Deriving the registers from the host's wall clock instead (what this
//!   emulator used to do) means the clock runs at whatever multiple of real
//!   time the emulator happens to be running at — 60× too fast headless, and
//!   frozen while the emulator is paused. ax6's `rtc3test` measures the tick
//!   interval with the Game Boy's own timer and requires 1000 ms ± 1 ms.
//! * **Across a shutdown**, the elapsed wall time is added on when the save is
//!   reloaded, from the timestamp in the `.sav` footer — see
//!   [`crate::mbc::battery`]. That is the coin cell.
//!
//! ## The counter chain
//!
//! The five registers are *counters*, not a normalised time. Each one is a
//! plain binary counter of its own physical width that carries into the next
//! only when it rolls over from its natural maximum:
//!
//! | register | width | carries at | wraps at |
//! |---|---|---|---|
//! | seconds  | 6 bits (`$3F`) | 59 → 0 | 63 → 0, **no carry** |
//! | minutes  | 6 bits (`$3F`) | 59 → 0 | 63 → 0, **no carry** |
//! | hours    | 5 bits (`$1F`) | 23 → 0 | 31 → 0, **no carry** |
//! | day      | 9 bits (day-low + `DH` bit 0) | — | 511 → 0, sets `DH` bit 7 |
//!
//! So a game that writes 62 to the seconds register sees 63 a second later and
//! 0 the second after that, with the minutes untouched. This is exactly what
//! `rtc3test`'s "range tests" check, and it falls out of modelling counters
//! rather than storing a `SystemTime`.
//!
//! `DH` bit 6 halts the clock; bit 7 is the day-counter overflow flag and is
//! sticky (only a write clears it).
//!
//! References: Pan Docs, "MBC3" (<https://gbdev.io/pandocs/MBC3.html>);
//! ax6's `rtc3test` test descriptions
//! (<https://github.com/aaaaaa123456789/rtc3test/blob/master/tests.md>).

use crate::mbc::battery::{now_secs, RtcState};

/// Console T-cycles in one RTC second. The cartridge's crystal is independent
/// of the console, so this is *real* time: it does not double in CGB
/// double-speed mode (the caller passes real-time cycles).
pub const CYCLES_PER_SECOND: u32 = 4_194_304;

/// `DH` bit 6 — the clock is stopped while this is set.
const HALT: u8 = 0x40;

/// `DH` bit 7 — the day counter has passed 511. Sticky.
const CARRY: u8 = 0x80;

/// Which bits of each register physically exist. Everything else reads back 0
/// whatever was written (`rtc3test` "Valid bits").
const MASKS: [u8; 5] = [0x3F, 0x3F, 0x1F, 0xFF, 0xC1];

/// Index of the day-high/flags register within the five.
const DH: usize = 4;

/// Advance one link of the counter chain by `n` ticks, returning how many times
/// it carried into the next link.
///
/// `top` is the value it rolls over *from* (carrying); `wrap` is its physical
/// modulus. A value loaded above `top` — which only software can produce —
/// counts on up to `wrap - 1` and then wraps to 0 **without** carrying, because
/// the carry is generated by the comparator that spots `top`, not by the
/// counter's own overflow.
fn advance_counter(v: &mut u8, n: u64, top: u8, wrap: u16) -> u64 {
    if n == 0 {
        return 0;
    }
    let mut n = n;
    if *v > top {
        // Out of range: run up to the physical limit and wrap, no carry.
        let to_wrap = wrap as u64 - *v as u64;
        if n < to_wrap {
            *v += n as u8;
            return 0;
        }
        n -= to_wrap;
        *v = 0;
        if n == 0 {
            return 0;
        }
    }
    let period = top as u64 + 1;
    let to_carry = period - *v as u64;
    if n < to_carry {
        *v += n as u8;
        return 0;
    }
    n -= to_carry;
    *v = (n % period) as u8;
    1 + n / period
}

/// The five RTC registers plus the sub-second divider that drives them.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Rtc {
    /// Live counters: seconds, minutes, hours, day-low, day-high/flags.
    regs: [u8; 5],
    /// The snapshot the game reads through `$A000-$BFFF`.
    latch: [u8; 5],
    /// T-cycles elapsed within the current second. Frozen while halted, which
    /// is what makes the clock resume mid-second after being stopped
    /// (`rtc3test` "RTC off/400").
    subsec: u32,
}

impl Default for Rtc {
    fn default() -> Self {
        Rtc::new()
    }
}

impl Rtc {
    pub fn new() -> Rtc {
        Rtc {
            regs: [0; 5],
            latch: [0; 5],
            subsec: 0,
        }
    }

    fn halted(&self) -> bool {
        self.regs[DH] & HALT != 0
    }

    /// Advance by `cycles` T-cycles of real console time. Called once per
    /// instruction from the MMU.
    pub fn tick(&mut self, cycles: u32) {
        if self.halted() {
            return;
        }
        self.subsec += cycles;
        if self.subsec >= CYCLES_PER_SECOND {
            let seconds = (self.subsec / CYCLES_PER_SECOND) as u64;
            self.subsec %= CYCLES_PER_SECOND;
            self.advance(seconds);
        }
    }

    /// Add `seconds` to the counter chain. Used both for a normal tick (n = 1)
    /// and for the catch-up when a save is reloaded, so the wrap rules cannot
    /// differ between the two.
    fn advance(&mut self, seconds: u64) {
        if seconds == 0 {
            return;
        }
        let carry = advance_counter(&mut self.regs[0], seconds, 59, 64);
        let carry = advance_counter(&mut self.regs[1], carry, 59, 64);
        let carry = advance_counter(&mut self.regs[2], carry, 23, 32);
        self.advance_day(carry);
    }

    fn advance_day(&mut self, days: u64) {
        if days == 0 {
            return;
        }
        let day = ((self.regs[DH] as u64 & 1) << 8) | self.regs[3] as u64;
        let total = day + days;
        if total > 0x1FF {
            self.regs[DH] |= CARRY;
        }
        let day = total & 0x1FF;
        self.regs[3] = day as u8;
        self.regs[DH] = (self.regs[DH] & !1) | ((day >> 8) as u8 & 1);
    }

    /// Read one latched register (`reg` is 0-4, i.e. RAM banks `$08-$0C`).
    pub fn read(&self, reg: usize) -> u8 {
        self.latch.get(reg).copied().unwrap_or(0xFF)
    }

    /// Write one register. Only the bits that exist are stored.
    pub fn write(&mut self, reg: usize, v: u8) {
        if reg >= 5 {
            return;
        }
        self.regs[reg] = v & MASKS[reg];
        if reg == 0 {
            // Writing the seconds register resets the sub-second divider: the
            // next tick is a full second away. Writing any *other* register
            // leaves the divider alone, so the tick still lands when it would
            // have. `rtc3test`'s "Sub-second writes" measures both cases to
            // 1.5 ms.
            self.subsec = 0;
        }
    }

    /// A write to `$6000-$7FFF` latches the counters.
    ///
    /// Pan Docs describes the sequence as "write `$00`, then `$01`", and that is
    /// what every game does — but it describes the idiom, not the decode. **Any
    /// single write latches**, whatever its value. CasualPokePlayer's
    /// `latch-rtc-test` is built to show exactly this: after one proper
    /// `$00`/`$01` pair it writes five random register values and then *one*
    /// random byte to `$6000` per row, and its reference dump has every row
    /// reading back what was just written. Requiring the `$00` → `$01` pair
    /// instead leaves every row showing the first latch — a screen of zeroes,
    /// measured here before this comment was written.
    pub fn write_latch(&mut self, _v: u8) {
        self.latch = self.regs;
    }

    /// The clock in the neutral shape the `.sav` footer stores, stamped now.
    pub fn snapshot(&self) -> RtcState {
        RtcState {
            regs: self.regs,
            latched: self.latch,
            timestamp: now_secs(),
        }
    }

    /// Restore from a `.sav` footer and carry the clock forward over the time
    /// the emulator was closed — the coin cell. A halted clock stays put, and a
    /// timestamp from the future (a save copied off a machine with a fast
    /// clock) advances nothing rather than going backwards.
    pub fn restore(&mut self, state: RtcState) {
        for (i, mask) in MASKS.iter().enumerate() {
            self.regs[i] = state.regs[i] & mask;
            self.latch[i] = state.latched[i] & mask;
        }
        self.subsec = 0;
        if !self.halted() {
            self.advance(now_secs().saturating_sub(state.timestamp));
        }
    }

    /// Restore from the legacy `.gbsave` format, whose only clock state is the
    /// UNIX second the counters were last at zero.
    pub fn restore_from_epoch(&mut self, zero: u64) {
        self.regs = [0; 5];
        self.latch = [0; 5];
        self.subsec = 0;
        self.advance(now_secs().saturating_sub(zero));
        self.latch = self.regs;
    }

    pub fn save_state(&self, w: &mut crate::savestate::Writer) {
        w.bytes(&self.regs);
        w.bytes(&self.latch);
        w.u32(self.subsec);
    }

    pub fn load_state(
        &mut self,
        r: &mut crate::savestate::Reader,
    ) -> Result<(), crate::savestate::StateError> {
        r.fill(&mut self.regs)?;
        r.fill(&mut self.latch)?;
        self.subsec = r.u32()?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn running() -> Rtc {
        let mut rtc = Rtc::new();
        // How a game latches: write $00 then $01 to $6000-$7FFF.
        rtc.write_latch(0);
        rtc.write_latch(1);
        rtc
    }

    fn tick_seconds(rtc: &mut Rtc, n: u32) {
        for _ in 0..n {
            rtc.tick(CYCLES_PER_SECOND);
        }
    }

    /// The tick interval is one second of *emulated* time, exactly.
    #[test]
    fn one_second_is_one_second_of_emulated_time() {
        let mut rtc = running();
        // One cycle short: nothing has happened yet.
        rtc.tick(CYCLES_PER_SECOND - 1);
        assert_eq!(rtc.regs[0], 0);
        rtc.tick(1);
        assert_eq!(rtc.regs[0], 1);
    }

    /// `rtc3test` "Seconds increment" / "Rollovers".
    #[test]
    fn the_counter_chain_rolls_over_at_255_days_23_59_59() {
        let mut rtc = running();
        rtc.write(0, 59);
        rtc.write(1, 59);
        rtc.write(2, 23);
        rtc.write(3, 0xFF);
        rtc.write(4, 0x00);
        tick_seconds(&mut rtc, 1);
        assert_eq!(rtc.regs, [0, 0, 0, 0x00, 0x01]);
    }

    /// `rtc3test` "Overflow" and "Overflow stickiness": day 511 -> 0 sets the
    /// carry flag, and it survives further ticks.
    #[test]
    fn the_day_counter_overflow_flag_is_sticky() {
        let mut rtc = running();
        rtc.write(0, 59);
        rtc.write(1, 59);
        rtc.write(2, 23);
        rtc.write(3, 0xFF);
        rtc.write(4, 0x01); // day 511
        tick_seconds(&mut rtc, 1);
        assert_eq!(rtc.regs[3], 0);
        assert_eq!(rtc.regs[4] & 0xC1, CARRY);
        // A whole further day must not clear it.
        tick_seconds(&mut rtc, 86_400);
        assert_eq!(rtc.regs[4] & CARRY, CARRY);
    }

    /// `rtc3test` "Invalid value tick": an out-of-range time just counts on.
    #[test]
    fn an_out_of_range_time_ticks_without_carrying() {
        let mut rtc = running();
        rtc.write(0, 60);
        rtc.write(1, 63);
        rtc.write(2, 28);
        rtc.write(3, 7);
        tick_seconds(&mut rtc, 1);
        assert_eq!(rtc.regs[..4], [61, 63, 28, 7]);
    }

    /// `rtc3test` "Invalid rollovers": a counter that overflows its physical
    /// width wraps to 0 and does **not** carry.
    #[test]
    fn an_overflowing_counter_wraps_without_carrying() {
        let mut rtc = running();
        rtc.write(0, 63);
        rtc.write(1, 30);
        tick_seconds(&mut rtc, 1);
        assert_eq!(rtc.regs[..2], [0, 30], "seconds 63 -> 0, minutes untouched");

        let mut rtc = running();
        rtc.write(0, 59);
        rtc.write(1, 63);
        rtc.write(2, 5);
        tick_seconds(&mut rtc, 1);
        assert_eq!(rtc.regs[..3], [0, 0, 5], "minutes 63 -> 0, hours untouched");

        let mut rtc = running();
        rtc.write(0, 59);
        rtc.write(1, 59);
        rtc.write(2, 31);
        rtc.write(3, 9);
        tick_seconds(&mut rtc, 1);
        assert_eq!(rtc.regs[..4], [0, 0, 0, 9], "hours 31 -> 0, day untouched");
    }

    /// `rtc3test` "High minutes" / "High hours": a carry *into* an out-of-range
    /// counter still increments it normally.
    #[test]
    fn a_carry_into_an_out_of_range_counter_increments_it() {
        let mut rtc = running();
        rtc.write(0, 59);
        rtc.write(1, 61);
        tick_seconds(&mut rtc, 1);
        assert_eq!(rtc.regs[..2], [0, 62]);

        let mut rtc = running();
        rtc.write(0, 59);
        rtc.write(1, 59);
        rtc.write(2, 27);
        tick_seconds(&mut rtc, 1);
        assert_eq!(rtc.regs[..3], [0, 0, 28]);
    }

    /// `rtc3test` "Valid bits": bits that do not exist read back as 0.
    #[test]
    fn only_the_bits_that_exist_are_writable() {
        let mut rtc = running();
        for reg in 0..5 {
            rtc.write(reg, 0xFF);
        }
        rtc.write_latch(0);
        rtc.write_latch(1);
        assert_eq!(
            (0..5).map(|i| rtc.read(i)).collect::<Vec<_>>(),
            vec![0x3F, 0x3F, 0x1F, 0xFF, 0xC1]
        );
    }

    /// `rtc3test` "Sub-second writes": a write to the seconds register restarts
    /// the divider; a write to any other register does not.
    #[test]
    fn only_a_seconds_write_resets_the_sub_second_divider() {
        let mut rtc = running();
        rtc.tick(CYCLES_PER_SECOND / 2);
        rtc.write(0, 10);
        rtc.tick(CYCLES_PER_SECOND / 2);
        assert_eq!(rtc.regs[0], 10, "half a second after a seconds write");
        rtc.tick(CYCLES_PER_SECOND / 2);
        assert_eq!(rtc.regs[0], 11);

        let mut rtc = running();
        rtc.tick(CYCLES_PER_SECOND / 2);
        rtc.write(1, 10); // minutes: the divider keeps running
        rtc.tick(CYCLES_PER_SECOND / 2);
        assert_eq!(rtc.regs[0], 1);
    }

    /// `rtc3test` "RTC off" and "RTC off/400": halting freezes the counters
    /// *and* the divider, so the clock resumes mid-second.
    #[test]
    fn halting_freezes_the_divider_too() {
        let mut rtc = running();
        rtc.tick(CYCLES_PER_SECOND * 6 / 10); // 600 ms into the second
        rtc.write(4, HALT);
        rtc.tick(CYCLES_PER_SECOND * 4); // four seconds, stopped
        assert_eq!(rtc.regs[0], 0, "a halted clock does not tick");
        rtc.write(4, 0);
        rtc.tick(CYCLES_PER_SECOND * 39 / 100); // 390 ms: not yet
        assert_eq!(rtc.regs[0], 0);
        rtc.tick(CYCLES_PER_SECOND * 2 / 100); // 410 ms total
        assert_eq!(rtc.regs[0], 1, "the remaining 400 ms, not a fresh second");
    }

    /// Reads see a *snapshot*, not the live counters.
    #[test]
    fn reads_come_from_the_latch_not_the_counters() {
        let mut rtc = running();
        tick_seconds(&mut rtc, 3);
        assert_eq!(rtc.read(0), 0, "still the old snapshot");
        rtc.write_latch(0);
        rtc.write_latch(1);
        assert_eq!(rtc.read(0), 3);
    }

    /// Any single write to `$6000-$7FFF` latches — not just a `$00`/`$01` pair.
    /// CasualPokePlayer's `latch-rtc-test` writes one random byte per row and
    /// expects every row to read back fresh values.
    #[test]
    fn any_single_write_latches() {
        for v in [0x00u8, 0x01, 0x14, 0x40, 0xD6, 0xFF] {
            let mut rtc = running();
            tick_seconds(&mut rtc, 7);
            rtc.write_latch(v);
            assert_eq!(rtc.read(0), 7, "a single ${v:02X} write must latch");
        }
    }

    /// The coin cell: time passes while the emulator is closed.
    #[test]
    fn the_clock_runs_while_the_emulator_is_shut() {
        let mut rtc = Rtc::new();
        let saved = RtcState {
            regs: [0, 0, 0, 0, 0],
            latched: [0, 0, 0, 0, 0],
            timestamp: now_secs() - (2 * 86_400 + 3 * 3600 + 4 * 60 + 5),
        };
        rtc.restore(saved);
        assert_eq!(rtc.regs, [5, 4, 3, 2, 0]);
    }

    /// ...but not while it is halted, and never backwards.
    #[test]
    fn a_halted_clock_does_not_move_while_the_emulator_is_shut() {
        let mut rtc = Rtc::new();
        rtc.restore(RtcState {
            regs: [1, 2, 3, 4, HALT],
            latched: [1, 2, 3, 4, HALT],
            timestamp: now_secs() - 100_000,
        });
        assert_eq!(rtc.regs, [1, 2, 3, 4, HALT]);

        let mut rtc = Rtc::new();
        rtc.restore(RtcState {
            regs: [7, 0, 0, 0, 0],
            latched: [7, 0, 0, 0, 0],
            timestamp: now_secs() + 10_000, // a save from the future
        });
        assert_eq!(rtc.regs, [7, 0, 0, 0, 0]);
    }

    /// A decade of catch-up must be arithmetic, not a loop, and must land on
    /// the same value one second at a time would.
    #[test]
    fn a_long_catch_up_matches_ticking_second_by_second() {
        let elapsed = 3 * 86_400 + 7 * 3600 + 41 * 60 + 13;
        let mut fast = Rtc::new();
        fast.restore(RtcState {
            regs: [0; 5],
            latched: [0; 5],
            timestamp: now_secs() - elapsed as u64,
        });
        let mut slow = running();
        tick_seconds(&mut slow, elapsed);
        assert_eq!(fast.regs, slow.regs);

        // And it does not hang on an absurd gap.
        let mut wild = Rtc::new();
        wild.restore(RtcState {
            regs: [0; 5],
            latched: [0; 5],
            timestamp: 0,
        });
        assert!(
            wild.regs[4] & CARRY != 0,
            "decades overflow the day counter"
        );
    }

    #[test]
    fn state_round_trips() {
        let mut rtc = running();
        rtc.write(0, 42);
        rtc.tick(1234);
        rtc.write_latch(1);
        let mut w = crate::savestate::Writer::new();
        rtc.save_state(&mut w);
        let mut back = Rtc::new();
        back.load_state(&mut crate::savestate::Reader::new(&w.buf))
            .unwrap();
        assert_eq!(back, rtc);
    }
}
